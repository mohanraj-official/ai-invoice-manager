-- AI Invoice Manager
-- PostgreSQL initial schema

CREATE TABLE IF NOT EXISTS invoices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    filename TEXT NOT NULL,
    mime_type TEXT NOT NULL,
    file_size BIGINT NOT NULL,

    sha256 TEXT NOT NULL UNIQUE,

    uploaded_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    drive_file_id TEXT,
    drive_file_url TEXT,

    drive_status TEXT NOT NULL DEFAULT 'not_uploaded'
);

CREATE TABLE IF NOT EXISTS invoice_extractions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    invoice_id BIGINT NOT NULL UNIQUE
        REFERENCES invoices(id) ON DELETE CASCADE,

    invoice_number TEXT,
    invoice_date TEXT,
    due_date TEXT,

    vendor_name TEXT,
    vendor_tax_id TEXT,
    vendor_address TEXT,

    customer_name TEXT,
    customer_tax_id TEXT,
    customer_address TEXT,

    currency TEXT,

    subtotal NUMERIC(18, 2),
    discount_total NUMERIC(18, 2),
    tax_total NUMERIC(18, 2),

    cgst NUMERIC(18, 2),
    sgst NUMERIC(18, 2),
    igst NUMERIC(18, 2),

    total NUMERIC(18, 2),

    payment_status TEXT NOT NULL DEFAULT 'unknown',
    category TEXT,

    billing_period_start TEXT,
    billing_period_end TEXT,

    line_items_json JSONB NOT NULL DEFAULT '[]'::jsonb,

    financial_check_status TEXT NOT NULL DEFAULT 'not_checked',

    extracted_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS upload_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    invoice_id BIGINT NOT NULL
        REFERENCES invoices(id) ON DELETE CASCADE,

    is_duplicate BOOLEAN NOT NULL DEFAULT FALSE,

    uploaded_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_invoices_uploaded_at
ON invoices(uploaded_at DESC);

CREATE INDEX IF NOT EXISTS idx_extractions_invoice_date
ON invoice_extractions(invoice_date);

CREATE INDEX IF NOT EXISTS idx_extractions_vendor
ON invoice_extractions(vendor_name);

CREATE INDEX IF NOT EXISTS idx_upload_events_invoice
ON upload_events(invoice_id);